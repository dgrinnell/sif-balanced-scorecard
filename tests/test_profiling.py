# --- end-to-end classification of an arbitrary table ----------------------


def test_classify_table_produces_reviewable_rows():
    df = pd.DataFrame(
        {
            "Hazard": [
                "Work near roof edge, approx 20 ft",
                "Racking breakers in 480V MCC room",
                "Repetitive lifting of cases",
            ],
            "Existing Controls": [
                "Warning line 6 ft from edge; buddy system",
                "LOTO EP-201, arc flash suit",
                "Lift training",
            ],
            "Frequency": ["monthly", "monthly", "daily"],
            "# Exposed": [2, 3, 10],
        }
    )
    review = classify_table(
        df, "Hazard", controls_col="Existing Controls",
        frequency_col="Frequency", workers_col="# Exposed",
    )
    assert len(review) == 3
    roof, panel, lifting = review.iloc[0], review.iloc[1], review.iloc[2]

    assert roof["high_energy"] == "yes" and not roof["direct_control"]
    assert "warning" in roof["control_type"]  # named, not credited
    assert panel["high_energy"] == "yes" and panel["direct_control"]
    assert lifting["high_energy"] == "no"
    # Every row explains itself.
    assert all(review["why_energy"].str.len() > 0)
    assert all(review["why_control"].str.len() > 0)


def test_classify_table_skips_blank_descriptions():
    df = pd.DataFrame({"Hazard": ["fall from roof", "", None]})
    assert len(classify_table(df, "Hazard")) == 1


def test_classify_table_errors_when_column_all_blank():
    df = pd.DataFrame({"Hazard": ["", None], "Other": ["a", "b"]})
    with pytest.raises(IngestError, match="hazard description"):
        classify_table(df, "Hazard")


def test_classify_table_errors_on_missing_column():
    with pytest.raises(IngestError, match="not in the file"):
        classify_table(pd.DataFrame({"a": [1]}), "Nope")
